using System.Globalization;
using System.Text.Json;

namespace MS43Logger.Core.Tuning;

/// <summary>An ECU RAM variable that a logger channel carries, and how to turn the channel's raw value into it.</summary>
public sealed record LiveInputSource(string Ram, string Channel, int PacketOffset, int Bits, long Mask, int Shift, long Add, long Max, bool Approximate, string Evidence)
{
    /// <summary>The value the ECU searches its axis with: <c>clamp(((raw &amp; Mask) &gt;&gt; Shift) + Add, 0, Max)</c>; a negative shift shifts left.</summary>
    public long Apply(long channelRaw)
    {
        var value = channelRaw & Mask;
        value = Shift >= 0 ? value >> Shift : value << -Shift;
        return Math.Clamp(value + Add, 0, Max);
    }
}

/// <param name="CountAddress">Address of the axis's count byte or word; the breakpoints follow it.</param>
public sealed record CatalogAxis(long CountAddress, int ElementBits, string Input);

/// <summary>One table read by the ECU's lookup library, with the RAM input of each axis (rows first).</summary>
public sealed record CatalogTable(long Data, string? Name, bool Interpolates, IReadOnlyList<CatalogAxis> Axes, string Source);

/// <summary>The per-table live inputs of one firmware (definitions/*_live_inputs.json, generated by scripts/make_live_inputs.py).</summary>
public sealed class LiveInputMap
{
    private static readonly Dictionary<string, string> BundledFiles = new(StringComparer.OrdinalIgnoreCase)
    {
        ["43X001"] = "ms43x001_live_inputs.json",
    };

    private readonly Dictionary<long, CatalogTable> _tables;
    private readonly Dictionary<long, IReadOnlyList<string>> _axisInputs;

    private LiveInputMap(string softwareId, IReadOnlyDictionary<string, string> provenance, IReadOnlyDictionary<string, LiveInputSource> inputs, IReadOnlyList<CatalogTable> tables)
    {
        SoftwareId = softwareId;
        Provenance = provenance;
        Inputs = inputs;
        Tables = tables;
        _tables = new Dictionary<long, CatalogTable>();
        foreach (var table in tables)
        {
            _tables.TryAdd(table.Data, table);
        }

        _axisInputs = tables.SelectMany(table => table.Axes)
            .GroupBy(axis => axis.CountAddress)
            .ToDictionary(group => group.Key, group => (IReadOnlyList<string>)group.Select(axis => axis.Input).Distinct(StringComparer.OrdinalIgnoreCase).ToList());
    }

    public string SoftwareId { get; }

    public IReadOnlyDictionary<string, string> Provenance { get; }

    /// <summary>Keyed by RAM variable name, case-insensitive.</summary>
    public IReadOnlyDictionary<string, LiveInputSource> Inputs { get; }

    public IReadOnlyList<CatalogTable> Tables { get; }

    public CatalogTable? FindTable(long data) => _tables.GetValueOrDefault(data);

    /// <summary>The distinct inputs every catalogue table searches the axis at <paramref name="countAddress"/> with.</summary>
    public IReadOnlyList<string> InputsOfAxis(long countAddress) => _axisInputs.GetValueOrDefault(countAddress) ?? Array.Empty<string>();

    public static LiveInputMap? LoadBundled(string? softwareId)
    {
        if (softwareId is null || !BundledFiles.TryGetValue(softwareId, out var fileName))
        {
            return null;
        }

        var assembly = typeof(LiveInputMap).Assembly;
        var resource = assembly.GetManifestResourceNames().SingleOrDefault(name => name.EndsWith(fileName, StringComparison.OrdinalIgnoreCase))
            ?? throw new FileNotFoundException($"Embedded input map '{fileName}' was not found.");
        using var stream = assembly.GetManifestResourceStream(resource)!;
        return Load(stream);
    }

    public static LiveInputMap Load(Stream json)
    {
        ArgumentNullException.ThrowIfNull(json);
        try
        {
            using var document = JsonDocument.Parse(json);
            var root = document.RootElement;
            var provenance = Required(root, "provenance").EnumerateObject().ToDictionary(p => p.Name, p => p.Value.GetString() ?? string.Empty);
            var inputs = Required(root, "inputs").EnumerateArray()
                .Select(i => new LiveInputSource(
                    Text(i, "ram"), Text(i, "channel"), (int)Hex(Text(i, "offset")), Required(i, "bits").GetInt32(), Hex(Text(i, "mask")),
                    Required(i, "shift").GetInt32(), Required(i, "add").GetInt64(), Required(i, "max").GetInt64(),
                    Required(i, "approximate").GetBoolean(), Text(i, "evidence")))
                .ToDictionary(i => i.Ram, StringComparer.OrdinalIgnoreCase);
            var tables = Required(root, "tables").EnumerateArray()
                .Select(t => new CatalogTable(
                    Hex(Text(t, "data")),
                    t.TryGetProperty("name", out var name) && name.ValueKind == JsonValueKind.String ? name.GetString() : null,
                    Required(t, "interp").GetBoolean(),
                    Required(t, "axes").EnumerateArray().Select(a => new CatalogAxis(Hex(a[0].GetString()!), a[1].GetInt32(), a[2].GetString()!)).ToList(),
                    Text(t, "source")))
                .ToList();
            return new LiveInputMap(Text(root, "softwareId"), provenance, inputs, tables);
        }
        catch (Exception error) when (error is JsonException or InvalidOperationException or FormatException or KeyNotFoundException or IndexOutOfRangeException or ArgumentException)
        {
            throw new InvalidDataException($"The live input map cannot be read: {error.Message}", error);
        }
    }

    private static JsonElement Required(JsonElement element, string name) =>
        element.TryGetProperty(name, out var value) ? value : throw new KeyNotFoundException($"the field \"{name}\" is missing");

    private static string Text(JsonElement element, string name) =>
        Required(element, name).GetString() ?? throw new KeyNotFoundException($"the field \"{name}\" is empty");

    private static long Hex(string text) =>
        long.Parse(text.StartsWith("0x", StringComparison.OrdinalIgnoreCase) ? text[2..] : text, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
}
